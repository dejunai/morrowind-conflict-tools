"""mwdialog_pathgrid.py - for --fix (Cell Fixes): pathgrids that walk people into what a later mod built.
A cell's pathgrid is made for the objects its plugin could see. When a mod that plugin doesn't know puts something
(a stall, a crate, a tree) across one of its paths, everyone walking that path runs into it and the game ends up
lifting them onto it. Such a path is sent round the new object where a clear, level way round exists; a path point
inside the new object is moved out of it; what can't be put right is left as it is and listed.
Only objects another mod placed or changed, unseen by the pathgrid's plugin, are looked at, so its own choices are
left alone. Nothing is ever taken out of a pathgrid.
"""
import hashlib
import itertools
import json
import math
import os
import struct

from mwdialog_footing import SUPPORT_TAGS, Surfaces, _state

PATHGRID_FIXES_FILE = "mwdialog_pathgrid_fixes.txt"

STEP, BODY, RADIUS = 32.0, 128.0, 24.0          # stepped onto without noticing; how tall and half how wide people are
CLEAR = 48.0                                    # a way round keeps this far from what is in the way
LEVEL_OFF = 64.0                                # its floor is at most this far above or below the path
SAMPLE = 48.0                                   # floor looked at this often along a new path
WET = -16.0                                     # floor lower than this is the sea
MOVE_REACH, MOVE_STEP = 320, 16                 # a point inside something is looked for a place this far around
STEEP = 0.5                                     # triangles less upright than this are floors, more are walls
OBSTACLE_TAGS = frozenset(("STAT", "ACTI", "CONT"))   # not doors: paths lead to them


def parse_pgrd(body):
    """(subrecords, points [x, y, z, autogenerated, pad], links [[point index]]) of a PGRD record's body."""
    subs, i = [], 0
    while i + 8 <= len(body):
        n = struct.unpack_from("<I", body, i + 4)[0]
        subs.append([body[i:i + 4].decode("latin-1"), body[i + 8:i + 8 + n]])
        i += 8 + n
    d = dict(subs)
    pgrp, pgrc = d.get("PGRP", b""), d.get("PGRC", b"")
    conns = struct.unpack("<%dI" % (len(pgrc) // 4), pgrc[:len(pgrc) // 4 * 4])
    points, links, c = [], [], 0
    for k in range(0, len(pgrp) // 16 * 16, 16):
        x, y, z, auto, n, pad = struct.unpack_from("<iiiBBh", pgrp, k)
        points.append([x, y, z, auto, pad])
        links.append(list(conns[c:c + n]))
        c += n
    return subs, points, links


def pack_pgrd(subs, points, links):
    out = b""
    for tag, data in subs:
        if tag == "DATA" and len(data) >= 12:
            data = data[:10] + struct.pack("<H", len(points)) + data[12:]
        elif tag == "PGRP":
            data = b"".join(struct.pack("<iiiBBh", p[0], p[1], p[2], p[3], len(links[i]), p[4])
                            for i, p in enumerate(points))
        elif tag == "PGRC":
            data = b"".join(struct.pack("<%dI" % len(lk), *lk) for lk in links)
        out += tag.encode("latin-1") + struct.pack("<I", len(data)) + data
    return b"PGRD" + struct.pack("<III", len(out), 0, 0) + out


def _cross(o, a, b):
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])


def _inside(pt, t):
    d1, d2, d3 = _cross(t[0], t[1], pt), _cross(t[1], t[2], pt), _cross(t[2], t[0], pt)
    return not ((d1 < 0 or d2 < 0 or d3 < 0) and (d1 > 0 or d2 > 0 or d3 > 0))


def _crosses(p, q, t):
    """The flat line p-q meets triangle t, seen from above."""
    if _inside(p, t) or _inside(q, t):
        return True
    for k in range(3):
        a, b = t[k], t[(k + 1) % 3]
        if _cross(p, q, a) * _cross(p, q, b) < 0 and _cross(a, b, p) * _cross(a, b, q) < 0:
            return True
    return False


def _lines(p, q):
    """The middle and both sides of someone walking from p to q (or standing at p)."""
    dx, dy = q[0] - p[0], q[1] - p[1]
    n = math.hypot(dx, dy)
    if n < 1e-6:
        return [((p[0] - RADIUS, p[1]), (p[0] + RADIUS, p[1])), ((p[0], p[1] - RADIUS), (p[0], p[1] + RADIUS))]
    ox, oy = -dy / n * RADIUS, dx / n * RADIUS
    return [(p[:2], q[:2]), ((p[0] + ox, p[1] + oy), (q[0] + ox, q[1] + oy)),
            ((p[0] - ox, p[1] - oy), (q[0] - ox, q[1] - oy))]


def _height(t, x, y):
    (ax, ay, az), (bx, by, bz), (cx, cy, cz) = t
    det = (by - cy) * (ax - cx) + (cx - bx) * (ay - cy)
    if abs(det) < 1e-6:
        return None
    u = ((by - cy) * (x - cx) + (cx - bx) * (y - cy)) / det
    v = ((cy - ay) * (x - cx) + (ax - cx) * (y - cy)) / det
    return u * az + v * bz + (1 - u - v) * cz if u >= -1e-6 and v >= -1e-6 and u + v <= 1 + 1e-6 else None


def _upright(t):
    (ax, ay, az), (bx, by, bz), (cx, cy, cz) = t
    ux, uy, uz, vx, vy, vz = bx - ax, by - ay, bz - az, cx - ax, cy - ay, cz - az
    nx, ny, nz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
    n = math.sqrt(nx * nx + ny * ny + nz * nz)
    return n > 1e-9 and abs(nz) / n < STEEP


def _stands_on(tris, pt):
    """pt is on one of these floors (a dock, a deck, a road edge): the path walks on the thing, not into it."""
    for t in tris:
        if not _upright(t) and _inside(pt, t):
            h = _height(t, pt[0], pt[1])
            if h is not None and abs(h - pt[2]) <= STEP:
                return True
    return False


def blocks(built, p, q):
    """A placed model ((triangles, box) as ModelShapes.placed gives them) is in the way of walking from p to q:
    a wall across the way between knee and head, or a floor at that height over it (a counter, a table).
    Something either end stands on is walked on, not into."""
    if built is None:
        return False
    tris, (x1, x2, y1, y2, z1, z2) = built
    lo, hi = min(p[2], q[2]) + STEP, max(p[2], q[2]) + BODY
    if z2 <= lo or z1 >= hi or max(p[0], q[0]) + RADIUS < x1 or min(p[0], q[0]) - RADIUS > x2 \
            or max(p[1], q[1]) + RADIUS < y1 or min(p[1], q[1]) - RADIUS > y2:
        return False
    if _stands_on(tris, p) or _stands_on(tris, q):
        return False
    lines = _lines(p, q)
    length = math.dist(p[:2], q[:2])
    samples = max(1, int(length // 16))
    for t in tris:
        tz1, tz2 = min(v[2] for v in t), max(v[2] for v in t)
        if tz2 <= lo or tz1 >= hi:
            continue
        if _upright(t):
            if any(_crosses(a, b, t) for a, b in lines):
                return True
            continue
        for a, b in lines:
            if not _crosses(a, b, t):
                continue
            for k in range(samples + 1):
                f = k / samples
                x, y = a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f
                h = _height(t, x, y)
                ground = p[2] + (q[2] - p[2]) * f
                if h is not None and ground + STEP < h < ground + BODY:
                    return True
    return False


def _near(entry, shapes, p, q):
    reach = shapes.radius(entry[2]) * abs(entry[1]) + RADIUS
    (x, y), (ax, ay), (bx, by) = entry[0][:2], p[:2], q[:2]
    dx, dy = bx - ax, by - ay
    f = 0.0 if dx == dy == 0 else max(0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(ax + dx * f - x, ay + dy * f - y) <= reach


PATHGRID_CACHE_FILE = "mwdialog_pathgrid_cache.json"
_CODE = ("mwdialog_pathgrid.py", "mwdialog_footing.py", "mwdialog_records.py", "mwdialog_tes3.py")


def _code_version():
    """What the results were worked out with: a change to any of these files starts the cache afresh."""
    h = hashlib.sha1()
    here = os.path.dirname(os.path.abspath(__file__))
    for name in _CODE:
        try:
            with open(os.path.join(here, name), "rb") as f:
                h.update(f.read())
        except OSError:
            h.update(name.encode())
    return h.hexdigest()


def load_pathgrid_cache(path):
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        if data.get("code") == _code_version() and isinstance(data.get("cells"), dict):
            return data["cells"]
    except (OSError, ValueError, AttributeError):
        pass
    return {}


def save_pathgrid_cache(path, cells):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump({"code": _code_version(), "cells": cells}, f)
    os.replace(tmp, path)


def _feed_block(h, blk):
    for s, d in blk:
        h.update(str(s).encode("latin-1", "replace") + b"\0")
        d = d if isinstance(d, (bytes, bytearray)) else str(d).encode("utf-8", "replace")
        h.update(len(d).to_bytes(4, "little") + d)


def cell_key(world, g, pi, off, author, known, around, patched, tag_of, model_of, shapes):
    """Everything one cell's check reads: its pathgrid and whose it is, every version of every object in it and the
    eight around it (and the patch's own), what those objects are and their meshes, and the land."""
    h = hashlib.sha1()
    h.update(repr((g, author, sorted(known))).encode())
    rec = world._record(pi, off)
    h.update(len(rec).to_bytes(4, "little") + rec)
    oids = set()
    for bk, vers in sorted(world.around(g).items(), key=lambda kv: repr(kv[0])):
        h.update(repr(bk).encode())
        for v in vers:
            h.update(repr(v[:3]).encode())
            _feed_block(h, v[3])
            oids.add(_state([v[3]])[2])
    for c in around:
        for bk, (grp, blk) in sorted((patched.get(("e",) + c) or {}).items(), key=lambda kv: repr(kv[0])):
            h.update(repr((c, bk, grp)).encode())
            _feed_block(h, blk)
            oids.add(_state([blk])[2])
    for oid in sorted(oids):
        model = model_of.get(oid)
        h.update(repr((oid, tag_of.get(oid), model)).encode())
        if model:
            h.update(shapes.digest(model).encode())
    for c in around:
        h.update(repr((c, world._land_of(c))).encode())
    return h.hexdigest()


def repair_pathgrids(world, pathgrids, patched, tag_of, model_of, shapes, progress=None, cache=None):
    """{(x, y): new PGRD record}, [what was put right], [what was left, to check] for the exterior pathgrids in
    pathgrids ((x, y) -> (plugin index, offset) of the one in use). patched: cell key -> {ref key: (group, block)}
    of what the patch already changes. progress(done, total), if given, is called every 50 cells and at the end.
    cache (from load_pathgrid_cache): each cell's result by everything it was worked out from; a cell whose
    inputs are all unchanged is taken from it, the rest are worked out and added. The fourth thing given back
    is how many cells were taken from it."""
    records, fixed, left, reused = {}, [], [], 0
    total = len(pathgrids)
    for n, (g, (pi, off)) in enumerate(sorted(pathgrids.items())):
        if progress and n % 50 == 0:
            progress(n, total)
        author, before = world.names[pi], len(fixed)
        known = frozenset(world.knows(author))
        around = [(g[0] + dx, g[1] + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1)]
        if not any(world.names[p] not in known for c in around for p, _o in world.ext_recs.get(c, ())) \
                and not any(patched.get(("e",) + c) for c in around):
            continue                             # nothing here its plugin couldn't see
        key = cell_key(world, g, pi, off, author, known, around, patched, tag_of, model_of, shapes) \
            if cache is not None else None
        hit = cache.get(key) if key else None
        if hit is not None:
            if hit[0]:
                records[g] = bytes.fromhex(hit[0])
            fixed += hit[1]
            left += hit[2]
            reused += 1
            continue
        lbefore = len(left)
        try:
            subs, points, links = parse_pgrd(world._record(pi, off))
            if not points or len(points) > 255 * 255:
                continue
            ox, oy = g[0] * 8192, g[1] * 8192
            at = [(p[0] + ox, p[1] + oy, float(p[2])) for p in points]
            placed, new = [], []
            for bk, vers in world.around(g).items():
                mine = [patched[ck][bk][1] for ck in {("e",) + tuple(v[1]) for v in vers} if bk in patched.get(ck, ())]
                pos, scale, oid, dele = _state([v[3] for v in vers] + mine)
                tag, model = tag_of.get(oid), model_of.get(oid)
                if dele or not pos or tag not in SUPPORT_TAGS or not model or "editormarker" in model \
                        or model.startswith("marker_"):
                    continue
                entry = (pos, scale, model, oid, tag)
                placed.append(entry)
                if tag not in OBSTACLE_TAGS:
                    continue
                if all(v[0] in known for v in vers):
                    continue                         # only this patch changed it (land followed): not another mod's
                seen = [v[3] for v in vers if v[0] in known]
                kpos, kscale, koid, kdele = _state(seen) if seen else (None, 1.0, "", True)
                ppos, pscale, poid, _pd = _state([v[3] for v in vers])
                if not kdele and kpos and ppos and koid == poid and kscale == pscale and \
                        all(abs(a - b) < 1 for a, b in zip(kpos[:3], ppos[:3])) and \
                        all(abs(a - b) < 0.01 for a, b in zip(kpos[3:], ppos[3:])):
                    continue                         # as the pathgrid's plugin saw it
                was = None
                if not kdele and kpos and tag_of.get(koid) in OBSTACLE_TAGS and model_of.get(koid):
                    was = (kpos, kscale, model_of[koid])
                by = next((v[0] for v in reversed(vers) if v[0] not in known), vers[-1][0])
                new.append((entry, was, by))
            if not new:
                continue

            def in_way(entry, was, p, q):
                if not _near(entry, shapes, p, q) or not blocks(shapes.placed(*entry[:3]), p, q):
                    return False
                return was is None or not blocks(shapes.placed(*was), p, q)    # in the way before too: theirs

            edges = sorted({tuple(sorted((a, b))) for a, lk in enumerate(links) for b in lk if b < len(points) and a != b})
            unreadable = sorted({e[3] for e, _w, _b in new if shapes.triangles(e[2]) is None
                                 and any(_near(e, shapes, at[a], at[b]) for a, b in edges)})
            where = f"#{g[0]},{g[1]} ({author}'s pathgrid)"
            for oid in unreadable:
                left.append(f"{where}: {oid}'s model can't be read; it may stand in a path")
            bad_points = {i: [n for n in new if in_way(n[0], n[1], at[i], at[i])] for i in range(len(at))}
            bad_points = {i: v for i, v in bad_points.items() if v}
            surf = None

            def floor(x, y, z):
                h = surf.floor(x, y, z + STEP)[0]
                return h if h > WET and abs(h - z) <= LEVEL_OFF else None

            walls = [e for e in placed if e[4] in OBSTACLE_TAGS]

            def clear(p, q):
                n = max(1, int(math.dist(p[:2], q[:2]) // SAMPLE))
                for k in range(n + 1):
                    f = k / n
                    if floor(p[0] + (q[0] - p[0]) * f, p[1] + (q[1] - p[1]) * f, p[2] + (q[2] - p[2]) * f) is None:
                        return False
                return not any(_near(e, shapes, p, q) and blocks(shapes.placed(*e[:3]), p, q) for e in walls)

            names = lambda hits: ", ".join(sorted({f"{e[3]} ({by})" for e, _w, by in hits}))   # noqa: E731
            links = [list(lk) for lk in links]
            stuck = set()
            if bad_points:
                surf = Surfaces(placed, world.land(), shapes)
            for i, hits in sorted(bad_points.items()):
                mates = [b for b in set(links[i]) | {a for a, lk in enumerate(links) if i in lk}
                         if b != i and b not in bad_points]
                spot = loose = None
                for r in range(MOVE_STEP, MOVE_REACH + 1, MOVE_STEP):
                    for k in range(16):
                        x, y = at[i][0] + r * math.cos(k * math.pi / 8), at[i][1] + r * math.sin(k * math.pi / 8)
                        if (math.floor(x / 8192), math.floor(y / 8192)) != g:
                            continue
                        h = floor(x, y, at[i][2])
                        if h is None or not clear((x, y, h), (x, y, h)):
                            continue
                        if loose is None:
                            loose = (x, y, h)        # clear itself; its paths may still need a way round
                        if all(clear((x, y, h), at[b]) for b in mates):
                            spot = (x, y, h)
                            break
                    if spot:
                        break
                spot = spot or loose
                if spot:
                    moved = math.dist(spot[:2], at[i][:2])
                    at[i] = spot
                    points[i][:3] = [round(spot[0] - ox), round(spot[1] - oy), round(spot[2])]
                    fixed.append(f"{where}: point {i} stood in {names(hits)}: moved {moved:.0f} units out of it")
                else:
                    stuck.add(i)
                    left.append(f"{where}: point {i} stands in {names(hits)} and has no clear place within "
                                f"{MOVE_REACH} units: left as it is")

            bad_edges = {}
            for a, b in edges:
                if a in stuck or b in stuck:
                    continue
                hit = [n for n in new if in_way(n[0], n[1], at[a], at[b])]
                if hit:
                    bad_edges[(a, b)] = hit
            if not bad_points and not bad_edges:
                continue
            if surf is None:
                surf = Surfaces(placed, world.land(), shapes)

            added = []
            for (a, b), hits in sorted(bad_edges.items()):
                boxes = [shapes.placed(*e[:3])[1] for e, _w, _b in hits]
                x1, x2 = min(bx[0] for bx in boxes) - CLEAR - RADIUS, max(bx[1] for bx in boxes) + CLEAR + RADIUS
                y1, y2 = min(bx[2] for bx in boxes) - CLEAR - RADIUS, max(bx[3] for bx in boxes) + CLEAR + RADIUS
                z = (at[a][2] + at[b][2]) / 2
                corners = []
                for cx, cy in ((x1, y1), (x1, y2), (x2, y1), (x2, y2)):
                    if (math.floor(cx / 8192), math.floor(cy / 8192)) != g:
                        continue
                    h = floor(cx, cy, z)
                    if h is not None:
                        corners.append((cx, cy, h))
                best = None
                for way in [[c] for c in corners] + [list(c) for c in itertools.permutations(corners, 2)]:
                    path = [at[a]] + way + [at[b]]
                    length = sum(math.dist(path[k], path[k + 1]) for k in range(len(path) - 1))
                    if (best is None or length < best[0]) and all(clear(path[k], path[k + 1])
                                                                   for k in range(len(path) - 1)):
                        best = (length, way)
                if best is None:
                    left.append(f"{where}: the path {a}-{b} runs into {names(hits)} and has no clear way round: "
                                f"left as it is")
                    continue
                for x_, y_ in ((a, b), (b, a)):
                    while y_ in links[x_]:
                        links[x_].remove(y_)
                chain = [a]
                for w in best[1]:
                    same = next((j for j in added if math.dist(at[j], w) < 16), None)
                    if same is None:
                        same = len(points)
                        points.append([round(w[0] - ox), round(w[1] - oy), round(w[2]), 0, 0])
                        links.append([])
                        at.append(w)
                        added.append(same)
                    chain.append(same)
                chain.append(b)
                for u, v in zip(chain, chain[1:]):
                    for x_, y_ in ((u, v), (v, u)):
                        if y_ not in links[x_]:
                            links[x_].append(y_)
                fixed.append(f"{where}: the path {a}-{b} ran into {names(hits)}: now goes round it "
                             f"({len(best[1])} point(s) added)")
            if len(fixed) == before:
                continue                             # nothing could be put right: the pathgrid stays as it is
            if any(len(lk) > 255 for lk in links):
                left.append(f"{where}: a point would have more than 255 paths; left as it is")
                continue
            records[g] = pack_pgrd(subs, points, links)
        finally:
            if key:
                rec = records.get(g)
                cache[key] = [rec.hex() if rec else None, fixed[before:], left[lbefore:]]
    if progress:
        progress(total, total)
    return records, fixed, left, reused
