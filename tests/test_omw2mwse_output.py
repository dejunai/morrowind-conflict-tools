@pytest.mark.parametrize("marks", [dict(header=True, require=False, register=False, manifest=False),
                                   dict(header=False, require=True, register=False, manifest=False),
                                   dict(header=False, require=False, register=True, manifest=False),
                                   dict(header=False, require=False, register=False, manifest=True)])
def test_each_marker_alone_marks_the_mod_and_everything_in_it(tmp_path, marks):
    gen = converted(tmp_path / "Data Files", **marks)
    assert P.omw_generated_dir(str(gen))
    for rel in ("main.lua", f"omw/scripts/{MOD}/LTLO_g.lua", "omw/main.lua.omw", "OMW2MWSE-REPORT.md"):
        assert P.omw_generated(str(gen / rel)), rel
    assert P.omw_generated(str(gen))


def test_runtime_is_generated_and_a_suite_mod_or_folder_name_is_not(tmp_path):
    df = tmp_path / "Data Files"
    converted(df)
    assert P.omw_generated(str(df / "MWSE" / "lib" / "omwcompat.lua"))
    assert P.omw_generated(str(df / "MWSE" / "lib" / "omwcompat" / "runtime.lua"))
    assert P.omw_generated(str(df / "MWSE" / "lib" / "omwcompat"))
    suite = put(df / "MWSE" / "mods" / "mwsuite" / "mwguard" / "main.lua", 'local x = require("mwguard.interop")\n')
    plain = put(df / "MWSE" / "mods" / "mwsuite" / "openmw" / "Hand" / "main.lua", "-- a hand port\nreturn\n")
    assert P.omw_generated(str(suite)) is None
    assert P.omw_generated(str(plain)) is None                     # the folder name alone means nothing
    assert P.omw_generated(str(df / "MWSE" / "lib" / "other.lua")) is None


def test_the_search_stops_at_mwse_mods(tmp_path):
    df = tmp_path / "Data Files"
    put(df / P.OMW_MANIFEST, "{}")                                 # not beside any loader: ignored
    put(df / "MWSE" / "mods" / P.OMW_MANIFEST, "{}")
    lua = put(df / "MWSE" / "mods" / "x" / "main.lua", "return\n")
    assert P.omw_generated(str(lua)) is None
    assert P.omw_marked_text(HEADER.encode()) and P.omw_marked_text(REQUIRE.encode())
    assert P.omw_marked_text(b"omwcompat.register({})") and P.omw_marked_text(b'local c = require "omwcompat"')
    assert P.omw_marked_text(b'require("omwcompat.runtime")')
    assert not P.omw_marked_text(b'require("openmw.world")') and not P.omw_marked_text(b'require("omwcompatx")')
    plain = converted(tmp_path / "Plain", header=False, require=False, register=False, manifest=False)
    assert P.omw_generated_dir(str(plain)) is None


