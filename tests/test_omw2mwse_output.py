# ---------------------------------------------------------------------------------------------- tidy
def plan(mod_dir):
    for d in (vt.NOTES, vt.ORPHAN_NORMALS, vt.NORMAL_PACKS, vt._TEX_INDEX, vt.REVIEW, vt.CONVERTED):
        d.clear()
    vt.CONVERTER["mode"] = None                      # the converter hand-off has its own tests
    return vt.plan_mod(str(mod_dir))


def test_tidy_leaves_a_converted_mod_alone(tmp_path, monkeypatch):
    monkeypatch.setattr(vt, "HERE", str(tmp_path))
    mod = tmp_path / "staging" / "Leave The Lights Off-57510-1-0"
    converted(mod)
    put(mod / f"{MOD}.omwaddon", b"TES3")
    put(mod / f"{MOD}.omwgame", b"TES3")
    moves = plan(mod)
    for src, _dst, _why in moves:
        rel = os.path.relpath(src, str(mod)).lower()
        assert not rel.startswith(("off", "mwse", f"{MOD}.omw".lower())), (rel, _why)
    assert str(mod) in vt.CONVERTED and str(mod) not in vt.REVIEW
    assert vt.CONVERTED[str(mod)][1] == [os.path.join("MWSE", "mods", "mwsuite", "openmw", MOD)]


def test_tidy_finds_scripts_set_aside_under_off(tmp_path, monkeypatch):
    monkeypatch.setattr(vt, "HERE", str(tmp_path))
    for off in (("Off", MOD, "OpenMW"), ("Off", "OpenMW", MOD)):   # omw2mwse's place, earlier tidy runs' place
        mod = tmp_path / "staging" / ("-".join(off) + "-1-0")
        put(mod / f"{MOD}.omwaddon", b"TES3")
        put(mod.joinpath(*off) / f"{MOD}.omwscripts", "GLOBAL: scripts/x.lua\n")
        moves = plan(mod)
        assert str(mod) not in vt.REVIEW, off                       # OpenMW-only, not converted: all of it to Off
        assert not any(d and d.endswith(".esp") for _s, d, _w in moves)      # and never renamed .esp
        names = sorted(os.path.basename(s) for s, d, _w in moves if d)
        assert names == sorted([f"{MOD}.omwaddon"] + ([f"{MOD}.omwscripts"] if off[1] == "OpenMW" else [])), off
        assert all(os.path.join("Off", MOD, "OpenMW") in d for _s, d, _w in moves if d), off      # omw2mwse's convention
    bare = tmp_path / "staging" / "Bare-1-0"
    put(bare / "Bare.omwaddon", b"TES3")
    assert any(d and d.endswith("Bare.esp") for _s, d, _w in plan(bare))   # no scripts anywhere: renamed


