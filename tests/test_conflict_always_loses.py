"""--cell-conflicts: "<plugin> always loses" in the interactive prompt adds the plugin to the generated conflict
list (mwdialog_check.conflict.blacklist.txt) at once and for good. Reading never makes or changes the file: it is
made by the first pick (header, the built-in OAAB_Saplings.esm, the pick), and a hand-written one is converted, entries
kept and backed up, when a pick is added to it."""
import builtins

from conftest import m
from test_conflict_confirm import _families

MINOR = {"place": [], "refs": [(("i", "house"), 1, False)], "settings": [], "doubled": False}
INCOMPATIBLE = {"place": [], "refs": [], "settings": [], "doubled": False,
                "incompatible": {"cells": {(1, 2)}, "evidence": {"terrain"}}}
HAND = ("; my own list\n; of plugins\nOAAB_Saplings.esm\nPorts Of Vvardenfell*.esp   ; the ports\n"
        "\nTrellis addon.ESP\n")


def _file(tmp_path):
    return tmp_path / m.CONFLICT_BLACKLIST_FILE


def _lines(tmp_path):
    return [ln.split(";", 1)[0].strip() for ln in _file(tmp_path).read_text(encoding="cp1252").splitlines()
            if ln.split(";", 1)[0].strip()]


def test_reading_a_missing_list_makes_nothing_and_the_built_in_entry_still_applies(tmp_path):
    assert m.read_conflict_blacklist(str(tmp_path)) == ["oaab_saplings.esm"]
    assert m.conflict_blacklisted("OAAB_Saplings.esm", m.read_conflict_blacklist(str(tmp_path)))
    assert not _file(tmp_path).exists()
    assert not [p for p in tmp_path.rglob("*") if p.is_file()]


def test_the_first_pick_makes_the_file_with_header_the_built_in_entry_and_the_pick(tmp_path):
    assert m.add_conflict_blacklist(str(tmp_path), "Mod.esp", "vs Other.esp") is True
    text = _file(tmp_path).read_text(encoding="cp1252")
    assert text.startswith("; " + m.CONFLICT_BLACKLIST_FILE + " - GENERATED by mwdialog_check.py")
    assert _lines(tmp_path) == ["OAAB_Saplings.esm", "Mod.esp"]
    assert m.read_conflict_blacklist(str(tmp_path)) == ["oaab_saplings.esm", "mod.esp"]
    assert m.add_conflict_blacklist(str(tmp_path), "Second.esp") is True        # later picks only append
    assert _lines(tmp_path) == ["OAAB_Saplings.esm", "Mod.esp", "Second.esp"]


def test_picking_the_built_in_plugin_writes_nothing(tmp_path):
    assert m.add_conflict_blacklist(str(tmp_path), "oaab_saplings.esm") is False
    assert not _file(tmp_path).exists()


def test_an_existing_generated_file_is_read_as_it_is(tmp_path):
    m.add_conflict_blacklist(str(tmp_path), "Mod.esp")
    before = _file(tmp_path).read_bytes()
    assert m.read_conflict_blacklist(str(tmp_path)) == ["oaab_saplings.esm", "mod.esp"]
    assert _file(tmp_path).read_bytes() == before


def test_a_hand_written_list_is_only_read_until_a_pick_converts_it_keeping_entries_and_backing_it_up(tmp_path):
    _file(tmp_path).write_bytes(HAND.encode("cp1252"))
    pats = m.read_conflict_blacklist(str(tmp_path))
    assert pats == ["oaab_saplings.esm", "ports of vvardenfell*.esp", "trellis addon.esp"]
    assert _file(tmp_path).read_text(encoding="cp1252") == HAND                 # a read changes nothing
    assert not [p for p in tmp_path.rglob("*") if p.is_file() and p.name != m.CONFLICT_BLACKLIST_FILE]
    assert m.add_conflict_blacklist(str(tmp_path), "Pick.esp") is True
    text = _file(tmp_path).read_text(encoding="cp1252")
    assert m.CONFLICT_BLACKLIST_MARK in text and "my own list" not in text
    assert "Ports Of Vvardenfell*.esp   ; the ports" in text            # an entry keeps its note
    backups = [p for p in tmp_path.rglob("*") if p.is_file() and p.name.startswith(m.CONFLICT_BLACKLIST_FILE)
               and p.name != m.CONFLICT_BLACKLIST_FILE]
    assert backups and any(p.read_text(encoding="cp1252") == HAND for p in backups)     # the old file, untouched
    assert _lines(tmp_path) == ["OAAB_Saplings.esm", "Ports Of Vvardenfell*.esp", "Trellis addon.ESP", "Pick.esp"]


def test_adding_keeps_every_entry_and_skips_one_already_covered(tmp_path):
    _file(tmp_path).write_bytes(HAND.encode("cp1252"))
    assert m.add_conflict_blacklist(str(tmp_path), "New [v2].esp", "vs Other.esp") is True
    assert m.add_conflict_blacklist(str(tmp_path), "Ports Of Vvardenfell V1.6.esp") is False
    assert _lines(tmp_path) == ["OAAB_Saplings.esm", "Ports Of Vvardenfell*.esp", "Trellis addon.ESP", "New [[]v2].esp"]
    pats = m.read_conflict_blacklist(str(tmp_path))
    assert m.conflict_blacklisted("new [v2].esp", pats) and not m.conflict_blacklisted("new v2.esp", pats)
    assert "chosen in --cell-conflicts" in _file(tmp_path).read_text(encoding="cp1252")


def _session(tmp_path, monkeypatch, pairs, answers, **over):
    args, plugins, masters = _families(tmp_path)
    for k, v in over.items():
        setattr(args, k, v)
    names = {n.lower(): n for n, _p in plugins}
    prompts = []

    def answer(prompt=""):
        prompts.append(prompt)
        return "n" if "Run --sort" in prompt else next(answers)
    monkeypatch.setattr(builtins, "input", answer)
    monkeypatch.setattr(m, "cell_conflicts_interactive", lambda a: True)
    monkeypatch.setattr(m, "main", lambda argv: 0)
    rc = m._conflict_session(args, pairs, names, masters, 1, plugins)
    return args, rc, prompts


def test_always_loses_is_offered_by_plugin_name_and_takes_effect_for_the_rest_of_the_run(tmp_path, monkeypatch, capsys):
    pairs = [(("a.esp", "b.esp"), MINOR), (("a.esp", "unrelated.esp"), MINOR), (("b.esp", "unrelated.esp"), MINOR)]
    args, rc, prompts = _session(tmp_path, monkeypatch, pairs, iter(["7", "1"]))   # A.esp always loses, then pair 3
    out = capsys.readouterr().out
    assert "[7] A.esp always loses   [8] B.esp always loses" in out
    assert "blacklist" not in out.lower().replace(m.CONFLICT_BLACKLIST_FILE.lower(), "")
    assert "A.esp always loses (1 more conflict(s) of it dropped) (saved in " in out
    assert [p for p in prompts if p == "  > "] == ["  > ", "  > "]     # pair 2 was never asked
    assert "A.esp vs Unrelated.esp" not in out
    assert _lines(tmp_path) == ["OAAB_Saplings.esm", "A.esp"]       # made by this first pick
    assert "a.esp" in m.read_conflict_blacklist(str(tmp_path))
    assert m.read_conflict_answers(str(tmp_path)).get("a.esp|b.esp") is None
    assert "Run --sort now" in "".join(prompts)                      # the ordering takes effect through --sort
    assert rc == 0


def test_the_other_plugin_can_be_the_one_that_always_loses(tmp_path, monkeypatch, capsys):
    _session(tmp_path, monkeypatch, [(("a.esp", "b.esp"), MINOR)], iter(["8"]))
    assert "b.esp" in m.read_conflict_blacklist(str(tmp_path))
    assert "a.esp" not in m.read_conflict_blacklist(str(tmp_path))


def test_incompatible_pairs_have_no_always_loses_choice(tmp_path, monkeypatch, capsys):
    _session(tmp_path, monkeypatch, [(("a.esp", "b.esp"), INCOMPATIBLE)], iter(["s"]))
    assert "always loses" not in capsys.readouterr().out
    assert not _file(tmp_path).exists()


def test_dry_run_does_not_save_an_always_loses_choice(tmp_path, monkeypatch, capsys):
    _session(tmp_path, monkeypatch, [(("a.esp", "b.esp"), MINOR)], iter(["7"]), dry_run=True)
    assert "(dry run: not saved)" in capsys.readouterr().out
    assert not _file(tmp_path).exists() and "a.esp" not in m.read_conflict_blacklist(str(tmp_path))


def test_replayed_answers_never_ask_or_change_the_blacklist(tmp_path, monkeypatch, capsys):
    args, plugins, masters = _families(tmp_path)
    names = {n.lower(): n for n, _p in plugins}
    m.write_conflict_answers(str(tmp_path), {"a.esp|b.esp": {"do": "order", "plugin": "A.esp", "pair": ["A.esp", "B.esp"]}})
    args.use_answers, args.defer_follow_up = True, True
    monkeypatch.setattr(m, "cell_conflicts_interactive", lambda a: False)
    monkeypatch.setattr(builtins, "input", lambda prompt="": "y" if "Run --sort" in prompt else (_ for _ in ()).throw(AssertionError(prompt)))
    monkeypatch.setattr(m, "main", lambda argv: 0)
    m._conflict_session(args, [(("a.esp", "b.esp"), MINOR)], names, masters, 1, plugins)
    assert not _file(tmp_path).exists()