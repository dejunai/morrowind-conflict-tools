"""The --play hash check (mwdialog_hashes): core .esm/.bsa baseline, our patches recorded when written, --play
refusing on a mismatch, --play-force starting anyway, --rebaseline-hashes. Temporary folders only; the game is
never started (subprocess.Popen is replaced)."""
import os
import types

import pytest

from conftest import _load, m

MH = _load("mwdialog_hashes")
T = _load("mwdialog_tes3")
PF = _load("mwdialog_patchfile")


@pytest.fixture
def game(tmp_path):
    data = tmp_path / "Data Files"
    data.mkdir()
    for name in ("Morrowind.esm", "Morrowind.bsa", "Tribunal.esm", "Tribunal.bsa", "Bloodmoon.esm", "Bloodmoon.bsa"):
        (data / name).write_bytes(name.encode() * 50)
    (tmp_path / "Morrowind.exe").write_bytes(b"MZ")
    return tmp_path, data


def write_our_patch(data, name="mwdialog_check Multipatch.esp", extra=()):
    path = str(data / name)
    PF.write_patch(path, [], [], [], extra=extra, description="test patch, generated by mwdialog_check.py")
    return path


def test_first_run_records_the_core_files_and_a_second_run_matches(game):
    root, data = game
    first = MH.verify(str(data))
    assert sorted(first["recorded"]) == sorted(MH.CORE) and not MH.failed(first)
    assert os.path.isfile(MH.record_path(str(data)))         # the test's own folder (conftest); never the game's
    assert not os.path.exists(root / MH.RECORD) and not os.path.exists(data / MH.RECORD)
    second = MH.verify(str(data))
    assert second["checked"] == 6 and not second["recorded"] and not MH.failed(second)
    assert any("6 file(s) match" in line for _e, line in MH.report(second))


def test_a_changed_core_file_is_a_mismatch_named_loudly(game):
    root, data = game
    MH.verify(str(data))
    (data / "Morrowind.esm").write_bytes(b"cleaned by someone")
    res = MH.verify(str(data))
    assert MH.failed(res) and [c[0] for c in res["changed"]] == ["Morrowind.esm"]
    text = "\n".join(line for _e, line in MH.report(res))
    assert "HASH CHECK FAILED - NOT starting the game" in text
    assert "CHANGED  Morrowind.esm (core file): SHA-256 was" in text
    assert "--rebaseline-hashes" in text and "--play-force" in text


def test_missing_tribunal_and_bloodmoon_are_skipped_quietly_but_morrowind_is_required(game):
    root, data = game
    for name in ("Tribunal.esm", "Tribunal.bsa", "Bloodmoon.esm", "Bloodmoon.bsa"):
        (data / name).unlink()
    res = MH.verify(str(data))
    assert sorted(res["recorded"]) == ["Morrowind.bsa", "Morrowind.esm"] and not MH.failed(res)
    assert not MH.failed(MH.verify(str(data)))
    (data / "Morrowind.bsa").unlink()
    res = MH.verify(str(data))
    assert res["missing"] == [("Morrowind.bsa", "core")] and MH.failed(res)


def test_our_patch_is_recorded_when_written_and_a_later_edit_is_a_mismatch(game):
    root, data = game
    path = write_our_patch(data)
    rec, _err = MH.read_record(MH.record_path(str(data)))
    assert rec["patches"]["mwdialog_check Multipatch.esp"]["sha256"] == MH.sha256_file(path)
    # a mod's own plugin written the same way is not ours: not recorded
    T.write_plugin_bytes(str(data / "SomeMod.esp"), open(path, "rb").read().replace(b"mwdialog_check", b"someone_else__"))
    rec, _err = MH.read_record(MH.record_path(str(data)))
    assert "SomeMod.esp" not in rec["patches"]
    assert not MH.failed(MH.verify(str(data)))
    with open(path, "ab") as f:
        f.write(b"edited in the CS")
    res = MH.verify(str(data))
    assert [(c[0], c[1]) for c in res["changed"]] == [("mwdialog_check Multipatch.esp", "patch")]
    assert "(our patch)" in "\n".join(line for _e, line in MH.report(res))
    write_our_patch(data)                                     # a rebuild records the new hash: expected
    assert not MH.failed(MH.verify(str(data)))


def test_a_recorded_patch_gone_from_data_files_is_missing_only_while_listed(game):
    root, data = game
    path = write_our_patch(data)
    os.remove(path)
    res = MH.verify(str(data), listed=["Morrowind.esm", "mwdialog_check Multipatch.esp"])
    assert res["missing"] == [("mwdialog_check Multipatch.esp", "patch")] and MH.failed(res)
    res = MH.verify(str(data), listed=["Morrowind.esm"])
    assert res["forgotten"] == ["mwdialog_check Multipatch.esp"] and not MH.failed(res)
    rec, _err = MH.read_record(MH.record_path(str(data)))
    assert rec["patches"] == {}


def play(monkeypatch, root, data, force=False, listed=()):
    started = []
    monkeypatch.setattr(m, "read_load_order", lambda args: list(listed))
    monkeypatch.setattr(m, "default_ini", lambda args: str(root / "no such Morrowind.ini"))
    monkeypatch.setattr(m.MP, "deploy_lua_tools", lambda dd: {"copied": [], "updated": [], "retired": [], "newer": []})
    monkeypatch.setattr(m.MP, "lua_prune_report", lambda dep: [])
    monkeypatch.setattr(m.subprocess, "run", lambda *a, **k: types.SimpleNamespace(stdout="steam.exe"))
    monkeypatch.setattr(m.subprocess, "Popen", lambda cmd, **kw: started.append(cmd))
    args = types.SimpleNamespace(data_dir=str(data), exe="Morrowind.exe", play_anyway=False, play_force=force,
                                 steam_appid="22320")
    return m.launch_game(args), started


def test_play_refuses_on_a_mismatch_and_starts_nothing(game, monkeypatch, capsys):
    root, data = game
    rc, started = play(monkeypatch, root, data)
    assert rc == 0 and len(started) == 1                       # first run: baseline recorded, game started
    (data / "Bloodmoon.bsa").write_bytes(b"replaced")
    rc, started = play(monkeypatch, root, data)
    err = capsys.readouterr().err
    assert rc == MH.REFUSED == 4 and started == []
    assert "HASH CHECK FAILED - NOT starting the game" in err and "CHANGED  Bloodmoon.bsa (core file)" in err


def test_play_force_prints_the_same_warning_and_starts_the_game(game, monkeypatch, capsys):
    root, data = game
    path = write_our_patch(data)
    MH.verify(str(data))
    with open(path, "ab") as f:
        f.write(b"x")
    rc, started = play(monkeypatch, root, data, force=True)
    err = capsys.readouterr().err
    assert rc == 0 and len(started) == 1
    assert "HASH CHECK FAILED - starting the game anyway (--play-force)" in err
    assert "CHANGED  mwdialog_check Multipatch.esp (our patch)" in err


def test_rebaseline_accepts_the_files_as_they_are(game, capsys):
    root, data = game
    MH.verify(str(data))
    (data / "Morrowind.esm").write_bytes(b"cleaned on purpose")
    assert m.main([str(data), "--rebaseline-hashes", "--dry-run", "--no-vortex"]) == 0
    assert MH.failed(MH.verify(str(data)))                     # dry run: nothing written
    assert m.main([str(data), "--rebaseline-hashes", "--no-vortex"]) == 0
    out = capsys.readouterr().out
    assert "Morrowind.esm: CHANGED, accepted" in out and "Tribunal.esm: unchanged" in out
    assert not MH.failed(MH.verify(str(data)))


def test_an_unreadable_record_fails_until_rebaselined(game):
    root, data = game
    rp = MH.record_path(str(data))
    os.makedirs(os.path.dirname(rp), exist_ok=True)
    with open(rp, "w") as f:
        f.write("{not json")
    res = MH.verify(str(data))
    assert MH.failed(res) and res["error"]
    MH.rebaseline(str(data))
    assert not MH.failed(MH.verify(str(data)))


def test_rebaseline_picks_up_a_patch_built_before_the_record_existed(game):
    root, data = game
    path = write_our_patch(data)
    os.remove(MH.record_path(str(data)))                      # as if built by a version without the record
    (data / "SomeMod.esp").write_bytes(open(path, "rb").read().replace(b"mwdialog_check", b"someone_else__"))
    lines = MH.rebaseline(str(data))
    assert any(line.startswith("  mwdialog_check Multipatch.esp: recorded") for line in lines)
    rec, _err = MH.read_record(MH.record_path(str(data)))
    assert list(rec["patches"]) == ["mwdialog_check Multipatch.esp"]


# ------------------------------------------------------------------------------- where the record is kept
def _valid_record(path):
    MH.write_record(path, dict(MH.empty_record(), core={"Morrowind.esm": MH._entry("0" * 64, 1)}))


def test_a_game_the_tools_are_not_installed_in_gets_a_record_beside_the_tools_never_in_the_game(
        game, tmp_path, monkeypatch):
    root, data = game
    monkeypatch.delenv(MH.RECORD_DIR_ENV, raising=False)
    monkeypatch.setattr(MH.MP, "GENERATED_DIR", str(tmp_path / "tools" / "generated"))
    rp = MH.record_path(str(data))
    assert os.path.dirname(rp) == str(tmp_path / "tools" / "generated")
    assert os.path.basename(rp) == MH.keyed_name(str(root)) != MH.RECORD
    MH.verify(str(data))
    write_our_patch(data)
    assert os.path.isfile(rp)
    assert not os.path.exists(root / MH.RECORD) and not os.path.exists(data / MH.RECORD)
    other = tmp_path / "Other Game" / "Data Files"                  # one record per game
    other.mkdir(parents=True)
    assert MH.record_path(str(other)) != rp


def test_a_record_an_older_version_left_in_the_game_folder_is_moved_and_still_used(game, tmp_path, monkeypatch):
    root, data = game
    monkeypatch.delenv(MH.RECORD_DIR_ENV, raising=False)
    monkeypatch.setattr(MH.MP, "GENERATED_DIR", str(tmp_path / "tools" / "generated"))
    _valid_record(str(root / MH.RECORD))
    rp = MH.record_path(str(data))
    assert not os.path.exists(root / MH.RECORD) and os.path.isfile(rp)
    rec, err = MH.read_record(rp)
    assert err is None and rec["core"]["Morrowind.esm"]["sha256"] == "0" * 64
    res = MH.verify(str(data))                                      # the old baseline is the one compared with
    assert [c[0] for c in res["changed"]] == ["Morrowind.esm"]


def test_a_caller_that_routes_state_path_keeps_its_place_and_gets_the_old_record(game, tmp_path, monkeypatch):
    root, data = game                                               # MWManager routes it to its outputs folder
    monkeypatch.delenv(MH.RECORD_DIR_ENV, raising=False)
    outputs = tmp_path / "outputs"
    monkeypatch.setattr(MH.MP, "state_path", lambda base, name: os.path.join(str(outputs), name))
    _valid_record(str(root / MH.RECORD))
    rp = MH.record_path(str(data))
    assert rp == str(outputs / MH.RECORD) and os.path.isfile(rp) and not os.path.exists(root / MH.RECORD)


def test_installed_in_the_game_the_record_stays_in_conflict_tools_generated(game, tmp_path, monkeypatch):
    root, data = game
    monkeypatch.delenv(MH.RECORD_DIR_ENV, raising=False)
    gen = root / "conflict-tools" / "generated"
    monkeypatch.setattr(MH.MP, "state_path", lambda base, name: os.path.join(str(gen), name)
                        if os.path.normcase(base) == os.path.normcase(str(root)) else os.path.join(base, name))
    assert MH.record_path(str(data)) == str(gen / MH.RECORD)


def test_a_caller_can_choose_the_folder(game, tmp_path, monkeypatch):
    root, data = game
    monkeypatch.delenv(MH.RECORD_DIR_ENV, raising=False)
    monkeypatch.setattr(MH, "RECORD_DIR", str(tmp_path / "mine"))
    assert MH.record_path(str(data)) == str(tmp_path / "mine" / MH.RECORD)
    monkeypatch.setattr(MH, "RECORD_DIR", None)
    monkeypatch.setenv(MH.RECORD_DIR_ENV, str(tmp_path / "env"))
    assert MH.record_path(str(data)) == str(tmp_path / "env" / MH.RECORD)
