"""vortex_tidy hands OpenMW-only mods (OpenMW scripts, no MWSE Lua) to the OpenMW converter (omw2mwse
--convert-omwscripts=<mode> <mod> --json, hardcode by default with --accept-hardcode-conversions); a mod with real
MWSE Lua is MWSE-first and its OpenMW files go to Off\\OpenMW\\ as always; a converter that isn't there is one
WARNING line and the usual move; a conflict (exit 4) is one WARNING line and the run goes on. The converter here is a
stub script that answers like the real one. Temporary folders only; tidy never runs on live data. Python 3.9+."""
import json
import os
import sys
import types

import pytest

from conftest import vt

MOD = "LeaveTheLightsOff"
HEADER = (f"-- {MOD}: MWSE loader generated by omw2mwse 0.2.1.\n"
          "-- Generated file: re-run omw2mwse instead of editing.\n")

STUB = r'''
import json, os, shutil, sys
args = sys.argv[1:]
with open(os.environ["STUB_LOG"], "a", encoding="utf-8") as f:
    f.write(json.dumps(args) + "\n")
mode = next(a.split("=", 1)[1] for a in args if a.startswith("--convert-omwscripts="))
d = next(a for a in args if not a.startswith("--"))
dry = "--dry-run" in args
name = os.path.basename(d)
fail = json.loads(os.environ.get("STUB_FAIL", "{}"))
code = fail.get(name.split("-")[0], 0)
if mode == "hardcode" and "--accept-hardcode-conversions" not in args:
    code = 3
mod = {"name": name.split("-")[0], "source": "Off/x/OpenMW", "status": "ok", "verdict": "ready", "rewrites": [],
       "conflicts": [], "files": {}, "alerts": []}
if code == 4:
    mod.update(status="conflict", conflicts=[{"path": "MWSE/mods/mwsuite/openmw/x/main.lua",
                                              "reason": "not written by omw2mwse"}])
elif code == 3:
    mod.update(status="refused", message="hard-code conversion needs --accept-hardcode-conversions")
elif code == 0 and not dry:
    out = os.path.join(d, "MWSE", "mods", "mwsuite", "openmw", mod["name"])
    os.makedirs(out)
    with open(os.path.join(out, "main.lua"), "w") as f:
        f.write(os.environ["STUB_HEADER"])
    off = os.path.join(d, "Off", mod["name"], "OpenMW")
    os.makedirs(off)
    for e in os.listdir(d):
        if e.lower().endswith(".omwscripts") or e.lower() == "scripts":
            shutil.move(os.path.join(d, e), os.path.join(off, e))
print(json.dumps({"tool": "omw2mwse", "version": "0.2.1", "command": "convert", "mode": mode, "dir": d,
                  "dryRun": dry, "changed": code == 0 and not dry, "exitCode": code, "alerts": [],
                  "mods": [mod]}, indent=1))
sys.exit(code)
'''


def put(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    (path.write_bytes if isinstance(data, bytes) else path.write_text)(data)


def openmw_mod(staging, name):
    mod = staging / f"{name}-1-0"
    put(mod / f"{name}.omwscripts", f"GLOBAL: scripts/{name}/g.lua\n")
    put(mod / "scripts" / name / "g.lua", "return {}\n")
    put(mod / f"{name}.omwaddon", b"TES3")
    put(mod / "readme.txt", "hi\n")
    return mod


@pytest.fixture
def tidy(tmp_path, monkeypatch):
    game = tmp_path / "game"
    (game / "Data Files").mkdir(parents=True)
    staging = tmp_path / "staging"
    staging.mkdir()
    home = tmp_path / "tools-home"
    (home / "tools").mkdir(parents=True)
    log = tmp_path / "calls.jsonl"
    monkeypatch.setenv("PATH", str(tmp_path / "empty-path"))          # no real converter on PATH
    monkeypatch.setenv("STUB_LOG", str(log))
    monkeypatch.setenv("STUB_HEADER", HEADER)
    monkeypatch.setattr(vt, "CONVERTER_HOME", str(home))
    monkeypatch.setattr(vt, "CONVERTER", dict(vt.CONVERTER))                # main() sets it; never leaks
    monkeypatch.setattr(vt, "vortex_info", lambda d: {})                      # never read the real Vortex state
    monkeypatch.setattr(vt, "interpreter_version", lambda cmd: (3, 11))       # the stub runs on any Python; tests below override
    monkeypatch.setattr(vt, "HERE", str(game))
    monkeypatch.setattr(vt, "CORE_MISSING", {})
    monkeypatch.setattr(vt, "JOURNAL", str(tmp_path / "journal.jsonl"))
    monkeypatch.setattr(vt, "PLAN", str(tmp_path / "vortex_tidy_plan.txt"))
    monkeypatch.setattr(vt, "AUDIT_ROOT", str(tmp_path / "audit"))
    monkeypatch.setattr(vt, "BLACKLIST_FILE", str(tmp_path / "bl.txt"))
    for d in (vt.NOTES, vt.REVIEW, vt.CONVERTED, vt.CONVERT):
        d.clear()

    def run(*extra):
        monkeypatch.setattr(vt.sys, "argv", ["vortex_tidy.py", "--staging", str(staging), "--no-lua", "--no-assets",
                                             *extra])
        return vt.main()

    def stub():
        (home / "tools" / "omw2mwse.py").write_text(STUB)

    def calls():
        return [json.loads(x) for x in log.read_text().splitlines()] if log.exists() else []

    def plan():
        return open(vt.PLAN, encoding="utf-8").read()
    return types.SimpleNamespace(run=run, stub=stub, calls=calls, plan=plan, staging=staging, home=home,
                                 tmp=tmp_path)


def test_openmw_only_mod_goes_to_the_converter_in_hardcode_mode_by_default(tidy, capsys):
    tidy.stub()
    mod = openmw_mod(tidy.staging, "Lights")
    assert tidy.run() == 0                                                     # plan: a dry run only
    plan = tidy.plan()
    assert "    convert with omw2mwse (hardcode): OpenMW-only, no MWSE Lua (Lights.omwscripts)" in plan
    assert "omw2mwse preview for Lights-1-0 (hardcode): Lights ok, verdict ready" in plan
    assert "Off\\OpenMW" not in plan and "readme" not in plan                  # nothing else in it moves
    (dry,) = tidy.calls()
    assert dry[:3] == ["--convert-omwscripts=hardcode", str(mod), "--json"]
    assert "--accept-hardcode-conversions" in dry and "--dry-run" in dry
    assert (mod / "Lights.omwscripts").exists()                               # plan mode changed nothing
    assert tidy.run("--apply", "--yes") == 0
    out = capsys.readouterr().out
    assert "converted Lights-1-0 with omw2mwse (hardcode): Lights ok, verdict ready (changed)" in out
    real = tidy.calls()[-1]
    assert "--dry-run" not in real and "--accept-hardcode-conversions" in real and "--json" in real
    assert (mod / "Off" / "Lights" / "OpenMW" / "Lights.omwscripts").exists()
    assert not os.path.exists(vt.JOURNAL) or "Lights" not in open(vt.JOURNAL).read()
    # the next run sees a converted mod: no second conversion, its .omwaddon is the converter's
    assert tidy.run() == 0
    assert "convert with omw2mwse" not in tidy.plan()


