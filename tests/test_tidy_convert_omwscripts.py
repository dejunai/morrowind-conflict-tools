    assert (tidy.staging / "Bad-1-0" / "Off" / "Bad" / "OpenMW" / "Bad.omwscripts").exists()
    assert vt.undo() == 0
    assert sorted(os.listdir(tidy.staging / "Bad-1-0")) == ["Bad.omwaddon", "Bad.omwscripts", "readme.txt", "scripts"]


