def test_converter_is_found_on_path_or_as_a_sibling_package(tidy, monkeypatch):
    assert vt.find_converter()[0] is None
    pkg = tidy.home.parent / "omw2mwse"                                        # sibling folder above the tools
    put(pkg / "__main__.py", "")
    put(pkg / "cli.py", "")
    cmd, env, where = vt.find_converter()
    assert cmd == [sys.executable, "-m", "omw2mwse"] and env["PYTHONPATH"].split(os.pathsep)[0] == str(tidy.tmp)
    bindir = tidy.tmp / "bin"
    launcher = bindir / ("omw2mwse.py")
