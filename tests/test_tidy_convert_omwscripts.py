def test_mwse_lua_is_detected_by_content_not_by_name(tidy):
    mod = tidy.staging / "Lib-1-0"
    put(mod / "MWSE" / "lib" / "something" / "util.lua", "return {}\n")         # an MWSE library: real Lua
    assert vt.has_mwse_lua(str(mod))
    gen = tidy.staging / "Gen-1-0"                                              # only converter output: not
    put(gen / "MWSE" / "mods" / "mwsuite" / "openmw" / MOD / "main.lua", HEADER)
    put(gen / "MWSE" / "lib" / "omwcompat.lua", "return {}\n")
    put(gen / "MWSE" / "lib" / "omwcompat" / "core.lua", "return {}\n")
    put(gen / "MWSE" / "config" / "x.json", "{}")
    assert not vt.has_mwse_lua(str(gen))
    named = tidy.staging / "Named-1-0"                                          # an MWSE folder with no Lua
    put(named / "MWSE" / "config" / "openmw.json", "{}")
    assert not vt.has_mwse_lua(str(named))


def test_missing_converter_is_one_warning_and_the_whole_package_goes_to_off(tidy, capsys):
    openmw_mod(tidy.staging, "Lights")
