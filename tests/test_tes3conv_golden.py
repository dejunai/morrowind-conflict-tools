"""Golden tests on plugins our tools write, read through tes3conv (Greatness7, MIT, pinned v0.4.1; optional: see
tes3diff.py). Each test builds its plugins from fixtures in a temp folder (never live data) and compares the normalized
record-level diff, as text, with the text written out here. They skip when tes3conv is not found.

tes3conv may lag the tes3 library: records or fields it does not know do not appear in these diffs."""
from conftest import m, misc, plugin, tes3
from test_cache import nif
from test_longpaths import LONGDIR, dds, fix, game, lp, long_model, misc as lmisc, put  # noqa: F401  (fixture: game)
from test_text_typos import TYPO, scan, topic


def test_the_converter_round_trips_a_fixture_plugin_byte_for_byte(tes3conv, tmp_path):
    src = tmp_path / "a.esp"
    plugin(str(src), [("Morrowind.esm", 79837557)], [misc("thing_a", 5, "Thing A")])
    again = tes3conv.write(tes3conv.records(src), tmp_path / "b.esp")
    assert open(again, "rb").read() == src.read_bytes()


def test_tidy_shortening_a_models_path_edits_one_field_of_the_esp(game, tes3conv):
    g, df = game
    mod = g / "staging" / "Long Mod"
    put(mod, "Meshes/%s/sub/thing.nif" % LONGDIR, b"")
    esp = mod / "LongMod.esp"
    esp.write_bytes(tes3(count=1) + lmisc("lm", long_model()))
    before = g / "before.esp"
    before.write_bytes(esp.read_bytes())
    issues, plan = lp.check_mod(str(mod), str(df), m, str(g))
    assert lp.apply_mod(str(mod), plan, m, str(g), "LongMod") == 1
    assert tes3conv.diff(before, esp) == (
        '~ MiscItem lm\n'
        '    mesh: "%s\\\\sub\\\\thing.nif" -> "lp\\\\thing_3c24df.nif"\n'
        'Summary: 0 added, 0 removed, 1 changed, 1 unchanged' % LONGDIR)


def test_the_esm_patch_check_writes_for_a_too_long_model_path(game, tes3conv, tmp_path):
    g, df = game
    put(df, "Meshes/%s/sub/thing.nif" % LONGDIR, nif("tx_ok.dds"))
    put(df, "Textures/tx_ok.dds", dds())
    esm = df / "Base.esm"
    esm.write_bytes(tes3(count=1) + lmisc("base_thing", long_model()))
    empty = tmp_path / "empty.esp"
    empty.write_bytes(tes3())
    fix(df, ["Base.esm"])
    assert tes3conv.diff(empty, df / m.PATCH_NAME) == (
        '~ Header #0\n'
        '    author: "t" -> "mwdialog_check"\n'
        '    description: "" -> "Dialogue fixes for master files, generated by mwdialog_check.py"\n'
        '    num_objects: 0 -> 1\n'
        '+ MiscItem base_thing\n'
        'Summary: 1 added, 0 removed, 1 changed, 0 unchanged')
    corrected = [r for r in tes3conv.records(df / m.PATCH_NAME) if r["type"] == "MiscItem"]
    assert corrected[0]["mesh"] == "lp\\thing_3c24df.nif"


def test_a_text_fix_lands_in_the_patch_only(tmp_path, tes3conv):
    esm = tmp_path / "AFFresh.esm"
    plugin(esm, [], topic(0, TYPO, "He sells fried kwama eggs."))
    w, _fixes = scan(("AFFresh.esm", esm))
    _esp_plans, esm_plans, _skipped, _manual = m.plan_fixes(w.r, w, [("AFFresh.esm", str(esm))], None, True)
    entries = []
    m.apply_plan(str(esm), "AFFresh.esm", esm_plans["AFFresh.esm"], w, [], collect=entries)
    patch = tmp_path / m.PATCH_NAME
    m.write_patch(str(patch), entries, [("AFFresh.esm", str(esm))], [], backup=False)
    empty = tmp_path / "empty.esp"
    empty.write_bytes(tes3())
    assert tes3conv.diff(empty, patch) == (
        '+ Dialogue af_test0\n'
        '+ DialogueInfo 01\n'
        '~ Header #0\n'
        '    author: "t" -> "mwdialog_check"\n'
        '    description: "" -> "Dialogue fixes for master files, generated by mwdialog_check.py"\n'
        '    num_objects: 0 -> 2\n'
        '    masters[0]: <absent> -> ["AFFresh.esm", %d]\n'
        'Summary: 2 added, 0 removed, 1 changed, 0 unchanged' % len(esm.read_bytes()))
    info = [r for r in tes3conv.records(patch) if r["type"] == "DialogueInfo"][0]
    assert "friend, Sky-Crest" in info["text"]


def test_write_patch_with_extra_records_and_a_master(tmp_path, tes3conv):
    base = tmp_path / "Base.esm"
    plugin(base, [], [misc("base_item", 7, "Base Item")])
    empty = tmp_path / "empty.esp"
    empty.write_bytes(tes3())
    patch = tmp_path / "Patch.esp"
    m.write_patch(str(patch), [], [("Base.esm", str(base))], [], backup=False, extra=[misc("base_item", 9, "Fixed Item")],
                  description="golden fixture patch")
    assert tes3conv.diff(empty, patch) == (
        '~ Header #0\n'
        '    author: "t" -> "mwdialog_check"\n'
        '    description: "" -> "golden fixture patch"\n'
        '    num_objects: 0 -> 1\n'
        '    masters[0]: <absent> -> ["Base.esm", %d]\n'
        '+ MiscItem base_item\n'
        'Summary: 1 added, 0 removed, 1 changed, 0 unchanged' % len(base.read_bytes()))
    item = [r for r in tes3conv.records(patch) if r["type"] == "MiscItem"][0]
    assert (item["name"], item["data"]["value"]) == ("Fixed Item", 9)